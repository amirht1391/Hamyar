    public static Loc I { get; } = new Loc();
    public event PropertyChangedEventHandler PropertyChanged;

    public string Lang { get; private set; } = "en";
    public bool IsRtl => Lang == "fa";
    /// <summary>Direction for CONTENT (the window frame stays LTR).</summary>
    public FlowDirection Flow => IsRtl ? FlowDirection.RightToLeft : FlowDirection.LeftToRight;
    public string this[string key] => Get(key);

    public static string Get(string key)
    {
        var d = I.Lang == "fa" ? Fa : En;
        if (d.TryGetValue(key, out var v)) return v;
        return En.TryGetValue(key, out var e) ? e : key;
    }

    public void SetLang(string lang)
    {
        Lang = lang;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(Flow)));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(Lang)));
    }

